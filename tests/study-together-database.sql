-- Real authenticated RPC/RLS tests with generated fixtures only. Always roll back.
begin;
do $$
declare u uuid[]; person uuid; rid uuid; second_room uuid; j jsonb; n integer; denied boolean; c integer;
begin
  select array_agg(gen_random_uuid()) into u from generate_series(1,8);
  foreach person in array u loop
    insert into auth.users(id,email,role,aud) values(person,'study-fixture-'||person||'@example.invalid','authenticated','authenticated');
  end loop;
  for n in 2..7 loop insert into public.quest_friendships(requester_id,addressee_id,status) values(u[1],u[n],'accepted'); end loop;
  perform set_config('request.jwt.claim.sub',u[1]::text,true);
  execute 'set local role authenticated';
  j:=public.quest_study('avatar',null,null,'{"lookId":4}');
  assert j->>'lookId'='4','Avatar saves to this account';
  j:=public.quest_study('create'); rid:=(j->'room'->>'id')::uuid;
  assert jsonb_array_length(j->'room'->'members')=1,'Room starts with only its host';
  perform public.quest_study('privacy',rid,null,'{"shareTask":true,"taskName":"HOST PRIVATE STUDY NAME"}');
  for n in 2..6 loop perform public.quest_study('invite',rid,u[n]); end loop;
  denied:=false;
  begin perform public.quest_study('invite',rid,u[7]); exception when raise_exception then denied:=true; end;
  assert denied,'Host plus five invited friends fills the room';
  denied:=false;
  begin perform public.quest_study('invite',rid,u[8]); exception when raise_exception then denied:=true; end;
  assert denied,'Nonfriend invitation denied';
  perform set_config('request.jwt.claim.sub',u[2]::text,true);
  j:=public.quest_study();
  assert j->'room'='null'::jsonb and jsonb_array_length(j->'invites')=1,'Invite is visible but room content is not';
  assert j::text not like '%HOST PRIVATE STUDY NAME%','Unaccepted invite cannot read a task';
  denied:=false;
  begin perform public.quest_study('presence',rid,null,'{"activity":"studying"}'); exception when insufficient_privilege then denied:=true; end;
  assert denied,'Invited user cannot publish presence';
  j:=public.quest_study('accept',rid);
  assert j->'room'->>'id'=rid::text,'Guest can accept';
  perform public.quest_study('presence',rid,null,'{"activity":"studying","elapsedSeconds":90,"taskName":"GUEST SECRET","shareTask":true}');
  j:=public.quest_study();
  assert j::text not like '%GUEST SECRET%','Malicious heartbeat cannot opt in to sharing';
  perform public.quest_study('privacy',rid,null,'{"shareTask":true,"taskName":"Shared reading"}');
  perform set_config('request.jwt.claim.sub',u[1]::text,true);
  j:=public.quest_study(); assert j::text like '%Shared reading%','Joined peer receives shared task';
  perform set_config('request.jwt.claim.sub',u[2]::text,true);
  perform public.quest_study('privacy',rid,null,'{"shareTask":false}');
  perform public.quest_study('presence',rid,null,'{"activity":"studying","taskName":"STALE SHARED NAME","elapsedSeconds":100}');
  perform set_config('request.jwt.claim.sub',u[1]::text,true);
  j:=public.quest_study(); assert j::text not like '%STALE SHARED NAME%','Delayed heartbeat cannot resurrect a hidden title';
  perform set_config('request.jwt.claim.sub',u[2]::text,true);
  denied:=false;
  begin perform public.quest_study('create'); exception when raise_exception then denied:=true; end;
  assert denied,'An account can only join one active room';
  denied:=false;
  begin perform public.quest_study('end',rid); exception when insufficient_privilege then denied:=true; end;
  assert denied,'Guest cannot end the room for everyone';
  select count(*) into c from public.quest_study_updates;
  assert c=1,'Realtime signal RLS exposes only the caller';
  assert not has_table_privilege('authenticated','public.quest_study_members','select'),'Raw task table is not readable';
  assert not has_table_privilege('authenticated','public.quest_study_members','insert'),'No direct membership or privacy writes';
  perform public.quest_study('leave',rid);
  j:=public.quest_study(); assert j->'room'='null'::jsonb,'Guest leaves immediately';
  denied:=false;
  begin perform public.quest_study('presence',rid,null,'{"activity":"studying"}'); exception when insufficient_privilege then denied:=true; end;
  assert denied,'Former member has no access';
  perform set_config('request.jwt.claim.sub',u[1]::text,true);
  perform public.quest_study('invite',rid,u[7]);
  perform set_config('request.jwt.claim.sub',u[7]::text,true);
  perform public.quest_study('accept',rid);
  perform public.quest_study('avatar',null,null,'{"lookId":5}');
  perform set_config('request.jwt.claim.sub',u[1]::text,true);
  j:=public.quest_study(); assert j::text like '%"lookId": 5%','Peers see the updated character';
  execute 'reset role';
  assert (select count(*)=6 from public.quest_study_members where room_id=rid and status in ('invited','joined')),'A freed seat is reusable without duplicates';
  assert (select task_name is null and not share_task from public.quest_study_members where room_id=rid and user_id=u[2]),'Leaving erases the stored task title';
  insert into public.quest_user_blocks(blocker_id,blocked_id) values(u[1],u[7]);
  assert (select status='removed' and task_name is null from public.quest_study_members where room_id=rid and user_id=u[7]),'Blocking immediately separates shared rooms';
  execute 'set local role authenticated';
  perform set_config('request.jwt.claim.sub',u[8]::text,true);
  j:=public.quest_study(); assert j->'room'='null'::jsonb and j->'invites'='[]'::jsonb,'Outsider cannot enumerate rooms';
  denied:=false;
  begin perform public.quest_study('accept',rid); exception when insufficient_privilege then denied:=true; end;
  assert denied,'Knowing a room UUID grants no access';
  perform set_config('request.jwt.claim.sub',u[1]::text,true);
  perform public.quest_study('end',rid);
  j:=public.quest_study(); assert j->'room'='null'::jsonb,'Ending returns host to solo';
  perform set_config('request.jwt.claim.sub',u[3]::text,true);
  j:=public.quest_study(); assert j->'invites'='[]'::jsonb,'Ending revokes outstanding invitations';
  j:=public.quest_study('create'); second_room:=(j->'room'->>'id')::uuid;
  execute 'reset role';
  update public.quest_study_rooms set expires_at=now()-interval '1 minute' where id=second_room;
  execute 'set local role authenticated';
  j:=public.quest_study(); assert j->'room'='null'::jsonb,'Expired sessions do not leak stale presence';
  j:=public.quest_study('create'); assert j->'room'->>'id'<>second_room::text,'Expired membership does not block a new room';
  execute 'reset role';
  assert not has_function_privilege('anon','public.quest_study(text,uuid,uuid,jsonb)','execute'),'Anonymous room access denied';
  assert (select count(*)=1 from pg_publication_tables where pubname='supabase_realtime' and tablename like 'quest_study_%'),'Only privacy-safe revision signals are published';
end $$;
select 'PASS: authenticated avatars, invites, six-seat cap, privacy, heartbeat races, RLS, blocks, leave, expiry and end' as result;
rollback;
